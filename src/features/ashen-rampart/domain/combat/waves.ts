/**
 * 灰燼の城壁 - 平原ステージのウェーブ定義（事前定義・乱数なし）
 *
 * 反復3 の再較正。マップが2レーン（北=短い直線／南=長い迂回・滞留あり）に
 * 変わり、守り手が経路上でブロックできるようになったため、反復2 までの
 * 単一レーン前提の較正値（総HP728・全エントリがレーン0）は意味を失った。
 * ここでの数・タイミング・レーン配分は、balance.test.ts の不変条件5本が
 * 同時に成立する点として実測で決めてある（難度は快適さではなく仮説成立の条件）。
 *
 * 実測（greedyStrategy・シード1〜20・全要求充足デッキ）:
 *
 * | 条件                     | 反復3 | 反復5 |
 * |--------------------------|-------|-------|
 * | 素直な戦略               | 14/20 | 12/20 |
 * | 経路外のみ               |  0/20 |  0/20 |
 * | 地上専用の攻撃札なし     |  6/20 |  6/20 |
 * | 対空なし                 |  0/20 |  0/20 |
 * | 範囲も貫通も無し         |  0/20 |  0/20 |
 * | 範囲だけ抜き             | 10/20 |  9/20 |
 * | 貫通だけ抜き             |  8/20 |  9/20 |
 *
 * （範囲だけを抜いても勝てるのは、貫通が代替するため。単独では拘束にならない）
 *
 * **表に載せていないが「配備後に何もしない戦略」は 10/20（反復5 の実測）。**
 * これは**撤回された指標であり、不変条件ではない**ので上の表とは分けてある。
 * 較正の閾値として使わないこと——この戦略が放棄しているのは山札が尽きた後の
 * 平均0.6枚の札だけで、20シード中11シードでは素直な戦略とランが完全に一致する
 * （run-simulation.ts の deployThenIdleStrategy の docstring に実測の全文がある）。
 *
 * **反復5 の再較正で動かしたのは次の3つだけ**（敵1体あたりの数値・レーン配分・
 * 鴉13体・LIFE_INITIAL には手を付けていない）:
 *
 * 1. 鴉の spawnIntervalTicks 10 → 18
 *    重厚型プリセットが 20ラン合計で鴉を125体漏らしていた（速攻型は15体）。
 *    鴉の流量が「弩砲3枚＋徹甲弩2枚」という速攻型の対空密度を前提にしており、
 *    落網で落として叩く重厚型では原理的に間に合っていなかった。プリセット間の
 *    勝率差 7（速攻型14・重厚型7）はほぼこの一点で説明できる。間隔を緩めたのは
 *    「対空を要求する」ことと「特定の対空の組み方だけを要求する」ことを分けるため。
 * 2. ウェーブ4 北の重装 2 → 4
 * 3. ウェーブ4 北の雑兵 2 → 4
 *    1 で落ちた難度を、鴉ではなく北の地上圧力で戻す。ここへ戻したのは、反復5 の
 *    摩耗（敵の射程攻撃）を持つのが北レーン専属の重装・雑兵だけであり、
 *    北の圧力を増やすことが摩耗の総量を増やすことと同義だからである。
 *    鴉の間隔だけを緩めた版（重装2・雑兵2 のまま）では経路外のみの戦略が
 *    0/20 → 2/20、速攻型の経路外のみが 1/20 → 3/20 まで上がり、
 *    「ブロックが要る」という不変条件の余裕が消えていた。
 *
 * **attackRange は動かしていない（重装1.5・雑兵1.2 のまま）。** 較正の測定器
 * （greedyStrategy）は攻撃札を shootingCellFor で置くため経路セルを優先し、
 * ほとんど経路外に置かない。そのため射程を 1.5→2.5→3.5 と上げても20シードの
 * 実測は1本も動かなかった。摩耗が効いていないのではなく測定器が拾わない
 * （経路外にしか置かない対照条件では20シード中8シードで経路外の弓兵が壊れる）。
 * 次に較正する人がここを回しても無駄なので、記録として残す。
 *
 * 敵の種類は増やしていない（5種のまま）。動かしたのは数・タイミング・
 * レーン配分だけで、敵1体あたりの数値にも手を付けていない。
 *
 * 敵数を変更したら描画密度（スタック表示）を必ず再計算すること
 * （PoC 設計書 `docs/superpowers/specs/2026-07-29-ashen-rampart-realtime-deck-poc-design.md` §9.3。
 * 反復5 の設計書には §9.3 が無い——あちらの §9 はログスキーマ v4 である）。
 * 反復5 の増加分は北レーンの重装・雑兵で、重装は 15tick 間隔・速度0.06（0.9セル差）、
 * 雑兵は 8tick 間隔・速度0.1（0.8セル差）と、いずれも束ねのしきい値 0.5セル
 * （enemy-stack.ts の STACK_DISTANCE）より広い。止められて詰まったときだけ
 * 束ねられるという既存の挙動から変わらないため、集約の実装は変えていない。
 *
 * **ただしこの分析が担保しているのは「同種内の間隔」だけである。**
 * `enemy-stack.ts` の束ね条件は `同じ enemyId かつ 距離 0.5 以内` で、
 * **異なる敵種は決して束ねられない。** `EnemyMarker.tsx` はセル座標を絶対配置する
 * だけでオフセットを持たないため、重装と雑兵が同一位置に来るとマーカーが完全に
 * 重なり、HPバーが読めなくなる。これはスタック集約では原理的に救えない。
 * 反復5 で北レーン（10セル）の体数は 4 → 8 に倍増し、雑兵（速度0.1）は
 * 重装（0.06）より速いので必ず追い抜く。交差の機会は概算で4倍になっている。
 * **ウェーブ4 開始直後の北レーンは目視確認が要る**（表示タスクと実プレイ判定への申し送り）。
 */
import { getEnemySpec } from './enemies';

export interface WaveEntry {
  enemyId: string;
  count: number;
  /** 同一エントリ内のスポーン間隔（tick） */
  spawnIntervalTicks: number;
  /** どのレーンに出すか。0 = 北（短い）、1 = 南（長い） */
  laneIndex: number;
}

export interface WaveDefinition {
  /** ラン開始からの絶対 tick。ウェーブは重なりうる */
  startTick: number;
  entries: WaveEntry[];
}

